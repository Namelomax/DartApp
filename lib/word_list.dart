import 'dart:convert';

import 'package:flutter/foundation.dart';
import 'package:http/http.dart' as http;

import 'ai_words.dart';
import 'game.dart';

/// A list of 51 301 Russian nouns, the game's source of truth for what counts
/// as a real noun.
///
/// Accepted guesses always come from it. Hidden words come from it too, unless
/// the model supplies a set this list can confirm.
const _nounsUrl =
    'https://raw.githubusercontent.com/Harrix/Russian-Nouns/main/dist/'
    'russian_nouns.txt';

/// Matches a word of exactly five Cyrillic letters, after normalization.
final _fiveCyrillicLetters = RegExp(r'^[а-я]{5}$');

/// Matches a single Cyrillic letter, after normalization.
final _cyrillicLetter = RegExp(r'^[а-я]$');

/// Whether [char] is a single Russian letter the board accepts.
///
/// Normalizes first, so uppercase input and "ё" both pass.
bool isRussianLetter(String char) =>
    _cyrillicLetter.hasMatch(normalizeWord(char));

/// Whether [word] has the shape of a Russian five-letter word.
///
/// Shape only — says nothing about the word being real or a noun.
bool isFiveLetterRussianWord(String word) =>
    _fiveCyrillicLetters.hasMatch(normalizeWord(word));

/// Folds a word or a player's guess into the single form the game compares.
///
/// Lowercases, trims, and treats "ё" as "е" so that "клёст" and "клест"
/// are the same word. Russian Wordle clones conventionally do this, since
/// most sources spell "ё" as "е" inconsistently.
String normalizeWord(String raw) =>
    raw.trim().toLowerCase().replaceAll('ё', 'е');

/// Where the round's hidden words ended up coming from.
enum WordSource {
  /// Generated by the model and confirmed against the noun dictionary.
  ai,

  /// The downloaded noun dictionary, unfiltered.
  dictionary,
}

/// Below this many confirmed words the generated set is too thin to use.
const _minimumAiWords = 5;

/// Loads the dictionaries and installs them into [game.dart].
///
/// Always downloads the noun list, which defines the legal guesses. Then, if
/// `.env` is filled in, asks the model for hidden-word candidates and keeps
/// the ones the noun list confirms.
///
/// Throws if the dictionary download fails, leaving the built-in fallback
/// words in place, so the caller can report it while the game stays playable.
/// A failure to generate words is not fatal: the dictionary is used instead.
Future<WordSource> loadWordLists({http.Client? client}) async {
  final httpClient = client ?? http.Client();
  try {
    final nouns = await _downloadNouns(httpClient);

    legalWords = nouns.toList();
    legalGuesses = const [];
    allLegalGuesses = nouns;

    _log('dictionary: ${nouns.length} five-letter nouns');

    if (!isAiConfigured) {
      _log('AI is not configured (.env); hidden words come from the '
          'dictionary.');
      return WordSource.dictionary;
    }

    try {
      final generated = await generateWords(
        count: aiWordCount,
        client: httpClient,
      );

      // The model's word is only used if the dictionary agrees it is a noun.
      // That is the actual guarantee: a model cannot be asked to prove it.
      final confirmed = generated.intersection(nouns);
      final unknown = generated.difference(nouns);

      _log('${generated.length} candidates -> ${confirmed.length} confirmed '
          'as nouns by the dictionary');
      if (unknown.isNotEmpty) {
        _log('not in the dictionary (${unknown.length}): '
            '${_sample(unknown, 20)}');
      }

      if (confirmed.length >= _minimumAiWords) {
        legalWords = confirmed.toList();
        _log('hidden-word pool: ${legalWords.length} AI words, e.g. '
            '${_sample(confirmed, 10)}');
        return WordSource.ai;
      }

      _log('only ${confirmed.length} confirmed, need at least '
          '$_minimumAiWords; falling back to the dictionary.');
    } on Object catch (error, stackTrace) {
      // A missing key, a 401, a rate limit, a model that answered in prose:
      // none of it should stop the game starting.
      _log('generation failed, falling back to the dictionary: $error');
      if (kDebugMode) debugPrintStack(stackTrace: stackTrace, maxFrames: 6);
    }

    _log('hidden-word pool: ${legalWords.length} dictionary words');
    return WordSource.dictionary;
  } finally {
    // Only close a client this function created; a caller-supplied one
    // (a test's mock, for instance) stays the caller's to manage.
    if (client == null) httpClient.close();
  }
}

/// Prefix on every log line from this file, so `[words]` filters the console.
const _tag = '[words]';

void _log(String message) => debugPrint('$_tag $message');

/// A short, comma-separated preview of [words] for a log line.
String _sample(Iterable<String> words, int limit) {
  final shown = words.take(limit).join(', ');
  final extra = words.length - limit;
  return extra > 0 ? '$shown … (+$extra)' : shown;
}

/// Downloads and parses the noun dictionary.
Future<Set<String>> _downloadNouns(http.Client httpClient) async {
  final response = await httpClient.get(Uri.parse(_nounsUrl));

  if (response.statusCode != 200) {
    throw http.ClientException(
      'Dictionary request failed with ${response.statusCode}',
      response.request?.url,
    );
  }

  // Decode UTF-8 explicitly rather than reading `response.body`, which
  // picks its codec from the Content-Type header and falls back to latin1
  // when the server doesn't declare a charset. That fallback mangles
  // Cyrillic into one replacement character per byte.
  final nouns = _fiveLetterWords(utf8.decode(response.bodyBytes));

  if (nouns.isEmpty) {
    throw const FormatException('Dictionary contained no five-letter words');
  }
  return nouns;
}

/// Extracts the normalized five-letter words from a newline-separated list.
Set<String> _fiveLetterWords(String body) => body
    .split('\n')
    .map(normalizeWord)
    .where(_fiveCyrillicLetters.hasMatch)
    .toSet();
